def runs(p, text, size=11, color=None, bold_all=False):
    for i, part in enumerate(re.split(r'\*\*', text)):
        if not part:
            continue
        r = p.add_run(part)
        r.font.size = Pt(size)
        r.font.name = '맑은 고딕'
        r._element.rPr.rFonts.set(qn('w:eastAsia'), '맑은 고딕')
        r.bold = bold_all or (i % 2 == 1)
        if color:
            r.font.color.rgb = RGBColor.from_string(color)
    return p


def para(text='', size=11, color=None, bold=False, before=None, style=None):
    p = d.add_paragraph(style=style)
    if before:
        p.paragraph_format.space_before = Pt(before)
    runs(p, text, size, color, bold)
    return p


def h1(t):
    return para(t, 14, NAVY, True, before=10)


def h2(t):
    return para(t, 12, BLUE, True, before=6)


def bullet(t):
    return para(t, 11, style='List Bullet')


def shade(el_pr, fill):
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), fill)
    el_pr.append(shd)


def box(lines, fill='EEF3FA', size=11):
    p = d.add_paragraph()
    for i, ln in enumerate(lines):
        if i:
            p.add_run().add_break()
        runs(p, ln, size)
    shade(p._p.get_or_add_pPr(), fill)
    return p


def table(header, rows, widths):
    t = d.add_table(rows=1 + len(rows), cols=len(header))
    t.style = d.styles['Table Grid'] if 'Table Grid' in [s.name for s in d.styles] else None
    tot = sum(widths)
    for ri, row in enumerate([header] + rows):
        for ci, txt in enumerate(row):
            c = t.cell(ri, ci)
            c.width = Emu(int(6400000 * widths[ci] / tot))
            p = c.paragraphs[0]
            for k, ln in enumerate(txt.split('\n')):
                if k:
                    p.add_run().add_break()
                if ri == 0:
                    runs(p, ln, 10, 'FFFFFF', True)
                else:
                    runs(p, ln, 10, None, ci == 0 and not ln.startswith('**') and len(header) > 2 and False)
            if ri == 0:
                shade(c._tc.get_or_add_tcPr(), NAVY)
            elif ci == 0:
                shade(c._tc.get_or_add_tcPr(), 'EEF3FA')
    d.add_paragraph()
    return t


def page_break():
    d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


